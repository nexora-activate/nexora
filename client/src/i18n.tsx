export interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  dir: "ltr" | "rtl";
  t: (key: MsgKey, vars?: Record<string, string | number>) => string;
  te: (serverError: string) => string;
  fmtDate: (iso: string) => string;
}

const I18nContext = createContext<I18n | null>(null);

function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : match,
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    // Lecture protégée : si le stockage du navigateur est bloqué, il lève
    // une erreur au lieu de répondre — sans ce filet, le premier affichage
    // plante et la page reste noire.
    try {
      if (typeof localStorage === "undefined") return "en";
      const saved = localStorage.getItem(LANG_KEY);
      return saved === "fr" || saved === "en" || saved === "es" || saved === "ar" || saved === "ru"
        ? saved
        : "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      // stockage indisponible : la langue reste appliquée pour la session
    }
  };

  const value: I18n = {
    lang,
    setLang,
    dir: lang === "ar" ? "rtl" : "ltr",
    t: (key, vars) => fill(DICTS[lang][key] ?? fr[key] ?? key, vars),
    te: (serverError) =>
      lang === "fr" ? serverError : (ERROR_TEXTS[serverError]?.[lang] ?? serverError),
    fmtDate: (iso) =>
      new Date(iso).toLocaleDateString(LOCALES[lang], {
        day: "numeric",
        month: "long",
        year: "numeric",
      }),
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n doit être utilisé dans <I18nProvider>");
  return ctx;
}
